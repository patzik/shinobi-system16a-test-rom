#!/usr/bin/env python3
"""Turn a MAME capture of Shinobi's attract mode into src/gfxdata.inc.

The capture file is a series of frames, each 0x800 bytes of sprite RAM
followed by 0x1000 bytes of palette RAM (big-endian words), recorded by
tools/capture.lua while the original game runs.

Output:
  tile_game_pal   1024 words: the game's background palettes (grey ramp
                  for palettes the attract mode never set)
  spr_page_tab    8 pointers, one sprite page per bank. Each page:
                  count.w, then per sprite 5 words (sprite RAM +0,+2,+4,+6,+8)
                  and its 16 palette words.
"""
import struct
import sys

FRAME = 0x800 + 0x1000
AREA_X0, AREA_X1 = 8, 312       # screen pixels
AREA_Y0, AREA_Y1 = 20, 196
GAP = 6
SPR_XBASE = 0xBD                # sprite x of screen column 0
MAX_PER_PAGE = 64               # one sprite palette per sprite


def load(path):
    d = open(path, "rb").read()
    for i in range(len(d) // FRAME):
        blk = d[i * FRAME:(i + 1) * FRAME]
        yield struct.unpack(">1024H", blk[:0x800]), struct.unpack(">2048H", blk[0x800:])


def main(cap, out):
    frames = list(load(cap))

    # --- background palettes: per palette, the frame where it is most filled in
    best = {}
    for _, pal in frames:
        for p in range(128):
            words = pal[p * 8:p * 8 + 8]
            score = sum(1 for w in words[1:] if w & 0x7FFF)
            if score and score > best.get(p, (0, None))[0]:
                best[p] = (score, words)
    grey = [0x0000] + [((v * 2) & 0xF) * 0x111 | ((v & 1) * 0x7000) for v in range(4, 32, 4)]
    tile_pal = []
    for p in range(128):
        tile_pal += list(best[p][1]) if p in best else grey

    # --- sprites: unique (bank, offset, pitch), tallest version, own palette
    found = {}
    for spr, pal in frames:
        for e in range(128):
            w = spr[e * 8:e * 8 + 8]
            bot, top = w[0] >> 8, w[0] & 0xFF
            if bot > 0xF0:
                break
            if top >= bot or w[3] & 0x8000:          # skip empty and flipped
                continue
            pitch = w[2]
            if pitch == 0 or pitch >= 0x8000:
                continue
            col = (w[4] >> 8) & 0x3F
            if col == 0x3F:                          # shadow sprites
                continue
            bank = (w[4] >> 4) & 7
            h = bot - top
            key = (bank, w[3], pitch)
            if key not in found or h > found[key][0]:
                found[key] = (h, pal[0x400 + col * 16:0x400 + col * 16 + 16])

    # drop entries whose data is covered by a taller entry (top-clipped copies)
    items = []
    for (bank, ofs, pitch), (h, pal16) in found.items():
        covered = any(b == bank and p == pitch and o <= ofs and o + p * h2 >= ofs + pitch * h
                      and (o, h2) != (ofs, h)
                      for (b, o, p), (h2, _) in found.items())
        if not covered and h >= 6:
            items.append((bank, ofs, pitch, h, pal16))

    pages = []
    for bank in range(8):
        cand = sorted((i for i in items if i[0] == bank), key=lambda i: -(i[2] * 4 * i[3]))
        placed, shelves = [], []                     # shelves: [y, height, next_x]
        for it in cand:
            if len(placed) >= MAX_PER_PAGE:
                break
            wpx, h = it[2] * 4, it[3]
            spot = None
            for s in shelves:
                if h <= s[1] and s[2] + wpx <= AREA_X1:
                    spot = s
                    break
            if spot is None:
                y = shelves[-1][0] + shelves[-1][1] + GAP if shelves else AREA_Y0
                if y + h > AREA_Y1 or wpx > AREA_X1 - AREA_X0:
                    continue
                spot = [y, h, AREA_X0]
                shelves.append(spot)
            placed.append((spot[2], spot[0], it))
            spot[2] += wpx + GAP
        pages.append(placed)
        print(f"bank {bank}: {len(cand)} candidates, {len(placed)} shown")

    with open(out, "w") as f:
        f.write("| Generated by tools/make_gfxdata.py from a MAME capture of\n")
        f.write("| Shinobi's attract mode. Do not edit by hand.\n\n")
        f.write("tile_game_pal:\n")
        for i in range(0, 1024, 8):
            f.write("        .word   " + ", ".join(f"0x{w:04x}" for w in tile_pal[i:i + 8]) + "\n")
        f.write("\nspr_page_tab:\n")
        for b in range(8):
            f.write(f"        .long   spr_page{b}\n")
        for b, placed in enumerate(pages):
            f.write(f"\nspr_page{b}:\n        .word   {len(placed)}\n")
            for slot, (x, y, (bank, ofs, pitch, h, pal16)) in enumerate(placed):
                w0 = ((y + h) << 8) | y
                w4 = (slot << 8) | (bank << 4) | 3
                f.write(f"        .word   0x{w0:04x}, 0x{SPR_XBASE + x:04x}, 0x{pitch:04x}, 0x{ofs:04x}, 0x{w4:04x}\n")
                f.write("        .word   " + ", ".join(f"0x{w:04x}" for w in pal16) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
